@torch.no_grad()
def evaluation_loss_for_if_answer_correct(model, text):
        model.eval()
        # set the parameters for testing how much are correct
        model_is_correct = 0
        total_tested = 0
        dummy_is_correct = 0
        print_20_sentences = 0
        # loop through each line and calculate for each equation
        for current_equation in text.splitlines():
            # dont calculate if there is no equal sign and add 1 to the
            # total as it has to be wrong
            if '=' not in current_equation:
                total_tested = total_tested + 1
                continue
            # split into the equation and the answer using the = sign
            equation, equation_answer = current_equation.split('=')
            final_equation =  equation + '='
            final_equation_answer = equation_answer.strip()
            # encode the equation part
            encoded_equation = torch.tensor([encode(final_equation)], dtype=torch.long, device=device)
            # get the same amount of answers as the amount of answers to the equation we have
            encoded_answers = model.generate(encoded_equation, max_new_tokens=len(final_equation_answer))
            # decode the answers to get the actual answers
            decoded_answers = decode(encoded_answers[0].tolist())
            # get just the answer part and get rid of the equation part
            answers_from_GPT = decoded_answers[len(final_equation):]
            # print out the first 10 useful equations 
            if 0 < print_20_sentences <= 20:
                print(f"{final_equation}{final_equation_answer}, the models answer is {answers_from_GPT}")
            print_20_sentences = print_20_sentences + 1
            # add to the correct variable if it is correct
            if (final_equation_answer == answers_from_GPT):
                model_is_correct = model_is_correct + 1
            # add to the total no matter what
            total_tested = total_tested + 1
            # get the dummy answer as a random number between the max and min anwwer
            dummys_answer = random.randint(0, 970299) # 198 for addition only, and 9801 for multiplication as well, 970,299 with brackets
            # if the dummy answer is right add to the dummy variable
            if (str(dummys_answer) == final_equation_answer):
                dummy_is_correct = dummy_is_correct + 1
        model.train()
        accuracy_of_the_model = model_is_correct/total_tested
        accuracy_of_the_dummy = dummy_is_correct/total_tested
        return accuracy_of_the_model, accuracy_of_the_dummy


# get the test data
testing_data = decode(val_data.tolist())
# get the accuracy of the test data
total_accuracy, total_dummy_accuracy = evaluation_loss_for_if_answer_correct(model, testing_data)
print(f"the accuracy of the model is: {total_accuracy:.2%}")
print(f"the accuracy of the dummy model is: {total_dummy_accuracy:.2%}")

